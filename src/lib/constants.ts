function normalizeKey(str: string): string {
  return str
    .replace(/^(دهم|یازدهم|دوازدهم)[:\s—-]+/, '')
    .replace(/^فصل\s*\d+[\s:—-]+/, '')
    .replace(/\(.*?\)/g, '')
    .trim();
}

export function getGoftarsForChapter(chapter: string): string[] {
  if (!chapter) return [];
  // 1. Exact match
  if (BIOLOGY_GOFTARS[chapter]) return BIOLOGY_GOFTARS[chapter];

  const cleaned = normalizeKey(chapter);
  if (BIOLOGY_GOFTARS[cleaned]) return BIOLOGY_GOFTARS[cleaned];

  // 2. Substring match
  const foundKey = Object.keys(BIOLOGY_GOFTARS).find(
    (k) => chapter.includes(k) || k.includes(cleaned) || cleaned.includes(k)
  );
  return foundKey ? BIOLOGY_GOFTARS[foundKey] : [];
}

export function getTopicsForSubjectAndChapter(subjectId: string, chapter: string): string[] {
  if (!chapter) return [];
  if (subjectId === 'bio') {
    return getGoftarsForChapter(chapter);
  }

  const topicMap =
    subjectId === 'chem'
      ? CHEMISTRY_TOPICS
      : subjectId === 'phy'
      ? PHYSICS_TOPICS
      : subjectId === 'math'
      ? MATH_TOPICS
      : null;

  if (!topicMap) return [];

  // Exact match
  if (topicMap[chapter]) return topicMap[chapter];

  const cleaned = normalizeKey(chapter);
  if (topicMap[cleaned]) return topicMap[cleaned];

  // Substring match
  const foundKey = Object.keys(topicMap).find(
    (k) => chapter.includes(k) || k.includes(cleaned) || cleaned.includes(k)
  );
  return foundKey ? topicMap[foundKey] : [];
}

