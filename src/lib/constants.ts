export function getBookTitle(subjectId: string, bookGrade: string): string {
  if (!bookGrade || bookGrade === 'all') return 'همه کتاب‌ها';
  const options = SUBJECT_BOOK_OPTIONS[subjectId] || [];
  const found = options.find((o) => o.id === bookGrade);
  if (found) return found.title;
  return bookGrade;
}

export function getChaptersForSubjectAndBook(subjectId: string, bookGrade: string = 'all'): string[] {
  const allChapters = SUBJECT_CHAPTERS[subjectId] || [];
  if (!bookGrade || bookGrade === 'all') return allChapters;
  return allChapters.filter((ch) => ch.startsWith(`${bookGrade}:`) || ch.startsWith(`${bookGrade} —`) || ch.includes(bookGrade));
}

